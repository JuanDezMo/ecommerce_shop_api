-- Órdenes con la dirección de envío copiada (snapshot) y sus ítems con el precio del momento de la compra.
CREATE TABLE orders (
    id                   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id              bigint         NOT NULL,
    status               varchar(20)    NOT NULL,
    payment_method       varchar(20)    NOT NULL,
    total                numeric(12, 2) NOT NULL,
    shipping_address     varchar(120)   NOT NULL,
    shipping_city        varchar(60)    NOT NULL,
    shipping_postal_code varchar(10)    NOT NULL,
    shipping_country     varchar(2)     NOT NULL,
    created_at           timestamptz    NOT NULL,

    CONSTRAINT fk_orders_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT ck_orders_status CHECK (status IN ('CONFIRMED')),
    CONSTRAINT ck_orders_payment_method CHECK (payment_method IN ('CARD', 'CASH', 'TRANSFER')),
    CONSTRAINT ck_orders_total CHECK (total >= 0)
);

-- Para GET /orders: órdenes de un usuario ordenadas por fecha
CREATE INDEX ix_orders_user_created_at ON orders (user_id, created_at DESC);

CREATE TABLE order_items (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id   bigint         NOT NULL,
    product_id bigint         NOT NULL,
    quantity   integer        NOT NULL,
    unit_price numeric(12, 2) NOT NULL,

    CONSTRAINT fk_order_items_order FOREIGN KEY (order_id) REFERENCES orders (id),
    CONSTRAINT fk_order_items_product FOREIGN KEY (product_id) REFERENCES products (id),
    CONSTRAINT ck_order_items_quantity CHECK (quantity > 0),
    CONSTRAINT ck_order_items_unit_price CHECK (unit_price >= 0)
);

CREATE INDEX ix_order_items_order ON order_items (order_id);
