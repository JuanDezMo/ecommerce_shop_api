-- Usuarios registrados. Las longitudes coinciden con los @Size de los DTOs (§6.6).
CREATE TABLE users (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email             varchar(100) NOT NULL,
    password_hash     varchar(60)  NOT NULL,          -- BCrypt siempre mide 60
    first_name        varchar(50)  NOT NULL,
    last_name         varchar(50)  NOT NULL,
    phone             varchar(15),                    -- opcional
    birth_date        date         NOT NULL,
    country           varchar(2)   NOT NULL,
    plan              varchar(10)  NOT NULL,
    experience_level  smallint     NOT NULL,
    newsletter        boolean      NOT NULL DEFAULT false,
    terms_accepted_at timestamptz  NOT NULL,
    status            varchar(10)  NOT NULL,
    created_at        timestamptz  NOT NULL,

    CONSTRAINT uk_users_email UNIQUE (email),
    CONSTRAINT ck_users_plan CHECK (plan IN ('BASIC', 'PRO')),
    CONSTRAINT ck_users_status CHECK (status IN ('ACTIVE', 'LOCKED')),
    CONSTRAINT ck_users_experience_level CHECK (experience_level BETWEEN 1 AND 5)
);
